"""
DeepEval-based evaluation of the tasteprofile RAG pipeline.

Reuses the eval rows already generated by run_ragas_food_eval.py
(eval/food_eval_ragas_input.json: user_input, response, retrieved_contexts, reference)
so this scores the same cases through a second, independently-recognized
eval framework (DeepEval) without re-running the LLM pipeline.

Run run_ragas_food_eval.py first to (re)generate eval/food_eval_ragas_input.json.
Run both from the repo root: python eval/run_ragas_food_eval.py, then
python eval/run_deepeval_food_eval.py.
"""
import json

from deepeval import evaluate
from deepeval.evaluate.configs import AsyncConfig, ErrorConfig
from deepeval.metrics import (
    AnswerRelevancyMetric,
    ContextualPrecisionMetric,
    ContextualRecallMetric,
    FaithfulnessMetric,
)
from deepeval.test_case import LLMTestCase

RAGAS_INPUT_JSON = "eval/food_eval_ragas_input.json"
SUMMARY_JSON = "eval/food_eval_deepeval_summary.json"

JUDGE_MODEL = "gpt-4o-mini"


def load_rows() -> list[dict]:
    with open(RAGAS_INPUT_JSON, "r", encoding="utf-8") as f:
        return json.load(f)


def build_test_cases(rows: list[dict]) -> list[LLMTestCase]:
    return [
        LLMTestCase(
            input=row["user_input"],
            actual_output=row["response"],
            retrieval_context=row["retrieved_contexts"],
            expected_output=row.get("reference", ""),
        )
        for row in rows
    ]


def main():
    rows = load_rows()
    print(f"Loaded {len(rows)} eval rows from {RAGAS_INPUT_JSON}")

    test_cases = build_test_cases(rows)

    metrics = [
        AnswerRelevancyMetric(model=JUDGE_MODEL),
        FaithfulnessMetric(model=JUDGE_MODEL),
        ContextualPrecisionMetric(model=JUDGE_MODEL),
        ContextualRecallMetric(model=JUDGE_MODEL),
    ]

    results = evaluate(
        test_cases=test_cases,
        metrics=metrics,
        async_config=AsyncConfig(run_async=True, throttle_value=2, max_concurrent=3),
        error_config=ErrorConfig(ignore_errors=True),
    )

    metric_scores: dict[str, list[float]] = {}
    for test_result in results.test_results:
        for metric_data in test_result.metrics_data:
            if metric_data.score is not None:
                metric_scores.setdefault(metric_data.name, []).append(metric_data.score)

    averages = {
        name: sum(scores) / len(scores)
        for name, scores in metric_scores.items()
        if scores
    }

    summary = {
        "rows_evaluated": len(test_cases),
        "judge_model": JUDGE_MODEL,
        "averages": averages,
    }

    with open(SUMMARY_JSON, "w", encoding="utf-8") as f:
        json.dump(summary, f, indent=2)

    print()
    print("DeepEval averages:")
    for name, score in averages.items():
        print(f"  {name}: {score:.4f}")
    print()
    print(f"Saved summary to {SUMMARY_JSON}")


if __name__ == "__main__":
    main()
